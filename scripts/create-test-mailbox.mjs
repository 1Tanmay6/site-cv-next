import fs from "node:fs";
import path from "node:path";
import nodemailer from "nodemailer";

const ENV_PATH = path.join(process.cwd(), ".env.local");
const force = process.argv.includes("--force");

if (fs.existsSync(ENV_PATH) && !force) {
  console.error(
    `${ENV_PATH} already exists. Re-run with --force to replace it with a new test mailbox.`
  );
  process.exit(1);
}

console.log("Creating an ephemeral Ethereal test mailbox...");

const account = await nodemailer.createTestAccount();
const transporter = nodemailer.createTransport({
  host: account.smtp.host,
  port: account.smtp.port,
  secure: account.smtp.secure,
  auth: {
    user: account.user,
    pass: account.pass,
  },
});

const info = await transporter.sendMail({
  from: account.user,
  to: account.user,
  subject: "Portfolio test mailbox ready",
  text: "This mailbox is used only for local contact-form testing.",
});

const contents = `# Generated by \`npm run mail:test-account\` on ${new Date().toISOString()}.
# These are ephemeral Ethereal test credentials, not production secrets.
# Re-run with \`npm run mail:test-account -- --force\` to generate a new mailbox.
# For deployment, replace every value with your provider's values.
SMTP_HOST=${account.smtp.host}
SMTP_PORT=${account.smtp.port}
SMTP_SECURE=${account.smtp.secure}
SMTP_USER=${account.user}
SMTP_PASSWORD=${account.pass}
MAIL_FROM=${account.user}
MAIL_TO=${account.user}
`;

fs.writeFileSync(ENV_PATH, contents, { mode: 0o600 });

console.log(`Wrote ${ENV_PATH}`);
console.log(`Ethereal login: https://ethereal.email/login`);
console.log(`Mailbox user: ${account.user}`);
console.log(`Mailbox password: ${account.pass}`);
console.log(`Test message preview: ${nodemailer.getTestMessageUrl(info)}`);
console.log(
  "Start the app with `npm run dev`, submit the contact form, then open the Ethereal inbox."
);
